def _cover(story, title, kind, styles):
    """Compact heading only; avoid a mostly-empty decorative cover page."""
    label = {
        'full_notes': 'Full structured notes', 'crisp_notes': 'Quick revision notes',
        'mindmap': 'Mind map', 'quiz': 'Practice quiz', 'flashcards': 'Flashcards',
    }.get(kind, kind.replace('_', ' ').title())
    story.append(Paragraph(_clean_inline(title or 'Lecture Study Notes'), styles['cover_title']))
    story.append(Paragraph(_clean_inline(label), styles['subtitle']))
    story.append(HRFlowable(width='100%', thickness=1.5, color=TEAL, spaceBefore=0, spaceAfter=5 * mm))


def _parse_mindmap(content):
    """Find a JSON mind-map tree in the supplied artifact content."""
    raw = (content or '').strip()
    candidates = [raw]
    match = re.search(r'\{.*\}', raw, re.S)
    if match:
        candidates.append(match.group(0))
    for candidate in candidates:
        try:
            data = json.loads(candidate)
            if isinstance(data, dict) and ('children' in data or 'label' in data or 'title' in data):
                return data
        except (json.JSONDecodeError, TypeError):
            pass
    return None


def _mindmap_blocks(tree, styles):
    """Draw a screen-like top-down mind map with connected, rounded topic blocks."""
    from reportlab.platypus import Flowable
    from reportlab.pdfbase.pdfmetrics import stringWidth

    def normalize(node):
        if not isinstance(node, dict):
            return {'label': str(node), 'children': []}
        label = str(node.get('label') or node.get('title') or 'Topic').strip()
        children = node.get('children', [])
        return {'label': label, 'children': [normalize(x) for x in children if isinstance(x, dict)] if isinstance(children, list) else []}

    root = normalize(tree)
    # Bound the drawing height by keeping the map as a single visual object;
    # wider/deeper maps are scaled slightly to stay readable on landscape A4.
    class MindMapCanvas(Flowable):
        def __init__(self, root):
            super().__init__()
            self.root = root
            self.height = 1

        def wrap(self, availWidth, availHeight):
            self.width = availWidth
            self.height = max(120 * mm, availHeight)
            self.avail_h = availHeight
            return availWidth, availHeight

        def _measure(self, node, depth=0):
            font = 9.2 if depth < 2 else 8.3
            max_text = max(stringWidth(line, 'Helvetica-Bold' if depth == 0 else 'Helvetica', font) for line in node['label'].splitlines() or [''])
            own = min(62 * mm, max(31 * mm, max_text + 12 * mm))
            children = node['children']
            child_widths = [self._measure(ch, depth + 1) for ch in children]
            gap = 7 * mm
            total = sum(child_widths) + max(0, len(child_widths)-1)*gap
            node['_boxw'] = own
            node['_subw'] = max(own, total)
            return node['_subw']

        def _draw_node(self, c, node, cx, top, depth, scale, maxdepth):
            boxw = node['_boxw'] * scale
            font = (10 if depth == 0 else 8.8 if depth == 1 else 8.1) * scale
            leading = font * 1.25
            text = node['label']
            # Wrap labels against node width using ReportLab Paragraph.
            style = ParagraphStyle('mm_%s_%s' % (depth, id(node)), fontName='Helvetica-Bold' if depth < 2 else 'Helvetica', fontSize=font, leading=leading,
                                   textColor=colors.white if depth == 0 else (NAVY if depth == 1 else INK), alignment=TA_CENTER, spaceAfter=0)
            para = Paragraph(_clean_inline(text), style)
            _, ph = para.wrap(boxw - 7*mm*scale, 1000)
            boxh = max((12 if depth == 0 else 10 if depth == 1 else 8.5)*mm*scale, ph + 5*mm*scale)
            y = top - boxh
            fill = NAVY if depth == 0 else (TEAL if depth == 1 else PALE if depth == 2 else colors.white)
            stroke = TEAL if depth < 2 else LINE
            c.setLineWidth(1.1*scale); c.setStrokeColor(stroke); c.setFillColor(fill)
            c.roundRect(cx-boxw/2, y, boxw, boxh, 2.5*mm*scale, stroke=1, fill=1)
            para.drawOn(c, cx-boxw/2 + 3.5*mm*scale, y+(boxh-ph)/2)
            children = node['children']
            if not children: return y
            child_top = y - 13*mm*scale
            child_gap = 7*mm*scale
            widths = [ch['_subw']*scale for ch in children]
            total = sum(widths) + max(0, len(widths)-1)*child_gap
            left = cx - total/2
            junction_y = y - 6.5*mm*scale
            c.setStrokeColor(TEAL); c.setLineWidth(1.05*scale)
            c.line(cx, y, cx, junction_y)
            c.line(left + widths[0]/2, junction_y, left + total - widths[-1]/2, junction_y) if len(children)>1 else None
            lowest = y
            for ch, cw in zip(children, widths):
                ccx = left + cw/2
                c.line(ccx, junction_y, ccx, child_top)
                child_bottom = self._draw_node(c, ch, ccx, child_top, depth+1, scale, maxdepth)
                lowest = min(lowest, child_bottom)
                left += cw + child_gap
            return lowest

        def draw(self):
            c = self.canv
            self._measure(self.root)
            full_w = self.root['_subw']
            # Keep some breathing room around the diagram; shrink only when needed.
            scale = min(1.0, (self.width - 8*mm) / max(full_w, 1))
            # For very deep maps, scale vertically just enough to fit the available page.
            depth = 0
            def getdepth(n, d=0):
                return max([d] + [getdepth(ch, d+1) for ch in n['children']])
            depth = getdepth(self.root)
            est_h = (depth + 1) * 25*mm
            scale = min(scale, max(0.48, (self.height - 8*mm) / est_h))
            top = self.height - 5*mm
            self._draw_node(c, self.root, self.width/2, top, 0, scale, depth)

    return [MindMapCanvas(root)]


def _content_blocks(content: str, styles):
    blocks = []
    lines = (content or '').replace('\r\n', '\n').replace('\r', '\n').split('\n')
    paragraph_lines = []

    def flush_paragraph():
        if paragraph_lines:
            text = ' '.join(part.strip() for part in paragraph_lines if part.strip())
            if text:
                blocks.append(Paragraph(_clean_inline(text), styles['body']))
            paragraph_lines.clear()

    for raw in lines:
        line = raw.strip()
        if not line:
            flush_paragraph()
            continue
        if line in ('---', '***', '___'):
            flush_paragraph()
            blocks.append(HRFlowable(width='100%', thickness=0.5, color=LINE, spaceBefore=2 * mm, spaceAfter=3 * mm))
            continue
        heading = re.match(r'^(#{1,3})\s+(.+)$', line)
        if heading:
            flush_paragraph()
            level = len(heading.group(1))
            style = styles[{1: 'h1', 2: 'h2', 3: 'h3'}[level]]
            blocks.append(Paragraph(_clean_inline(heading.group(2)), style))
            continue
        # Recognize common plain-text headings generated by LLMs.
        plain_heading = re.match(r'^(?:\d+[.)]\s+)?([A-Z][A-Z0-9 &:/()\-]{3,})$', line)
        if plain_heading and len(line) < 90:
            flush_paragraph()
            blocks.append(Paragraph(_clean_inline(line), styles['h2']))
            continue
        bullet = re.match(r'^(?:[-*•]|\d+[.)])\s+(.+)$', line)
        if bullet:
            flush_paragraph()
            is_number = bool(re.match(r'^\d+[.)]', line))
            marker = re.match(r'^(\d+)[.)]', line).group(1) + '.' if is_number else '•'
            blocks.append(Paragraph(f'<font color="#0F8B8D"><b>{marker}</b></font>  {_clean_inline(bullet.group(1))}', styles['bullet']))
            continue
        if re.match(r'^(Key takeaway|Important|Remember|Definition|In short|Summary)\s*:', line, re.I):
            flush_paragraph()
            label, value = line.split(':', 1)
            callout = Table([[Paragraph(f'<b>{_clean_inline(label)}:</b> {_clean_inline(value)}', styles['callout'])]], colWidths=[160 * mm])
            callout.setStyle(TableStyle([
                ('BACKGROUND', (0, 0), (-1, -1), PALE), ('BOX', (0, 0), (-1, -1), 0.5, LINE),
                ('LINEBEFORE', (0, 0), (0, -1), 2.5, TEAL), ('LEFTPADDING', (0, 0), (-1, -1), 4 * mm),
                ('RIGHTPADDING', (0, 0), (-1, -1), 4 * mm), ('TOPPADDING', (0, 0), (-1, -1), 3 * mm),
                ('BOTTOMPADDING', (0, 0), (-1, -1), 3 * mm),
            ]))
            blocks.append(KeepTogether([callout, Spacer(1, 2 * mm)]))
            continue
        paragraph_lines.append(line)
    flush_paragraph()
    return blocks



def _quiz_blocks(content: str, styles):
    """Format quiz_to_text output as distinct question cards with separated options and solutions."""
    lines = (content or "").replace("\r\n", "\n").replace("\r", "\n").split("\n")
    blocks = []
    title_seen = False
    current = None

    def flush():
        nonlocal current
        if not current:
            return
        card = []
        card.append(Paragraph(_clean_inline(current["question"]), styles["h3"]))
        for label, option in current["options"]:
            card.append(Paragraph(f'<font color="#0F8B8D"><b>{escape(label)}.</b></font>  {_clean_inline(option)}', styles["quiz_option"]))
        if current["answer"]:
            answer_table = Table([[Paragraph(f'<b>Correct answer:</b> {_clean_inline(current["answer"])}', styles["quiz_answer"])]], colWidths=[165*mm])
            answer_table.setStyle(TableStyle([("BACKGROUND", (0,0), (-1,-1), PALE), ("BOX", (0,0), (-1,-1), 0.5, LINE), ("LEFTPADDING", (0,0), (-1,-1), 4*mm), ("RIGHTPADDING", (0,0), (-1,-1), 4*mm), ("TOPPADDING", (0,0), (-1,-1), 2.5*mm), ("BOTTOMPADDING", (0,0), (-1,-1), 1*mm)]))
            card.extend([Spacer(1, 1.5*mm), answer_table])
        if current["explanation"]:
            card.extend([Spacer(1, 1.5*mm), Paragraph(f'<b>Solution:</b> {_clean_inline(current["explanation"])}', styles["body"])])
        blocks.append(KeepTogether(card))
        blocks.append(Spacer(1, 4*mm))
        current = None

    for raw in lines:
        line = raw.strip()
        if not line:
            continue
        q = re.match(r"^(\d+)[.)]\s+(.+)$", line)
        if q:
            flush()
            current = {"question": f"{q.group(1)}. {q.group(2)}", "options": [], "answer": "", "explanation": ""}
            continue
        opt = re.match(r"^([A-D])[.)]\s+(.+)$", line)
        if current and opt:
            current["options"].append((opt.group(1), opt.group(2)))
            continue
        answer = re.match(r"^(?:Correct answer|Answer)\s*:\s*(.+)$", line, re.I)
        if current and answer:
            current["answer"] = answer.group(1)
            continue
        explanation = re.match(r"^(?:Explanation|Solution)\s*:\s*(.+)$", line, re.I)
        if current and explanation:
            current["explanation"] = explanation.group(1)
            continue
        if current:
            current["question"] += " " + line
        elif not title_seen:
            blocks.append(Paragraph(_clean_inline(line), styles["h1"]))
            title_seen = True
    flush()
    return blocks

def create_study_pdf(title: str, kind: str, content: str) -> bytes:
    """Return a concise PDF for a generated study artifact."""
    buffer = BytesIO()
    normalized_kind = (kind or 'study_material').lower()
    doc = _StudyDocTemplate(buffer, title or 'Lecture Study Notes', normalized_kind,
        leftMargin=19 * mm, rightMargin=19 * mm, topMargin=23 * mm, bottomMargin=20 * mm,
        author='LectureMate')
    styles = _styles()
    story = []
    _cover(story, title or 'Lecture Study Notes', normalized_kind, styles)
    if normalized_kind == 'quiz':
        story.extend(_quiz_blocks(content or '', styles))
    elif normalized_kind == 'mindmap':
        tree = _parse_mindmap(content or '')
        if tree:
            story.extend(_mindmap_blocks(tree, styles))
        else:
            story.extend(_content_blocks(content or 'No mind map data was provided.', styles))
    else:
        story.extend(_content_blocks(content or 'No study material was provided.', styles))
    doc.build(story)
    return buffer.getvalue()
