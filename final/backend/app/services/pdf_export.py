"""Create polished, printable PDFs for LectureMate study artifacts.

Compatible with the existing three-argument API: create_study_pdf(title, kind, content).
Requires ReportLab, which is used for all PDF layout and pagination.
"""
from __future__ import annotations

import re
import json
from datetime import date
from io import BytesIO
from xml.sax.saxutils import escape

from reportlab.lib import colors
from reportlab.lib.enums import TA_CENTER, TA_LEFT
from reportlab.lib.pagesizes import A4, landscape
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import (
    BaseDocTemplate, PageTemplate, Frame, Paragraph, Spacer, PageBreak,
    KeepTogether, HRFlowable, Table, TableStyle, Flowable,
)

INK = colors.HexColor('#17243A')
NAVY = colors.HexColor('#172E55')
TEAL = colors.HexColor('#0F8B8D')
MUTED = colors.HexColor('#627086')
PALE = colors.HexColor('#EAF6F5')
LINE = colors.HexColor('#DCE4EC')
PAPER = colors.white


def _clean_inline(text: str) -> str:
    text = escape(text.strip())
    text = re.sub(r'\*\*(.+?)\*\*', r'<b>\1</b>', text)
    text = re.sub(r'(?<!\*)\*([^*]+)\*(?!\*)', r'<i>\1</i>', text)
    text = re.sub(r'`([^`]+)`', r'<font name="Courier">\1</font>', text)
    return text


class _StudyDocTemplate(BaseDocTemplate):
    def __init__(self, target, title: str, kind: str, **kwargs):
        self.page_size = landscape(A4) if kind == "mindmap" else A4
        super().__init__(target, pagesize=self.page_size, **kwargs)
        self.doc_title = title
        self.kind_label = {
            'full_notes': 'FULL STRUCTURED NOTES',
            'crisp_notes': 'QUICK REVISION NOTES',
            'mindmap': 'LECTURE MIND MAP',
            'quiz': 'PRACTICE QUIZ',
            'flashcards': 'FLASHCARDS',
        }.get(kind, kind.replace('_', ' ').upper())
        page_w, page_h = self.page_size
        frame = Frame(19 * mm, 19 * mm, page_w - 38 * mm, page_h - 39 * mm,
                      leftPadding=0, rightPadding=0, topPadding=4 * mm, bottomPadding=0,
                      id='main')
        self.addPageTemplates([PageTemplate(id='study', frames=[frame], onPage=self._draw_page)])

    def _draw_page(self, canvas, doc):
        canvas.saveState()
        w, h = self.page_size
        if doc.page == 1:
            canvas.setFillColor(NAVY)
            canvas.rect(0, h - 7 * mm, w, 7 * mm, stroke=0, fill=1)
        else:
            canvas.setStrokeColor(LINE)
            canvas.setLineWidth(0.6)
            canvas.line(19 * mm, h - 15 * mm, w - 19 * mm, h - 15 * mm)
            canvas.setFont('Helvetica-Bold', 8)
            canvas.setFillColor(NAVY)
            canvas.drawString(19 * mm, h - 12 * mm, 'LECTUREMATE  /  STUDY NOTES')
            canvas.setFont('Helvetica', 8)
            canvas.setFillColor(MUTED)
            canvas.drawRightString(w - 19 * mm, h - 12 * mm, self.kind_label)
        canvas.setStrokeColor(LINE)
        canvas.line(19 * mm, 14 * mm, w - 19 * mm, 14 * mm)
        canvas.setFont('Helvetica', 8)
        canvas.setFillColor(MUTED)
        canvas.drawString(19 * mm, 9 * mm, 'Generated by LectureMate  •  ' + date.today().strftime('%d %b %Y'))
        canvas.drawRightString(w - 19 * mm, 9 * mm, f'{doc.page}')
        canvas.restoreState()


